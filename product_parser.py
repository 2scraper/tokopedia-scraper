def total_results(html: str, shown: int = 0) -> Optional[int]:
    """Tokopedia publishes no result total. Always None, and deliberately so.

    Its search header looks like it does:

        "Menampilkan 1 - 60 barang dari total  untuk "kopi""
        ("Showing 1 - 60 items of total ___ for "kopi"")

    but the total is EMPTY on every capture — `dari total` followed by
    nothing. The range is printed, and it is not an oracle either: after one
    scroll the header claimed 61-180 while the DOM held 95 tiles. So there is
    no arithmetic completeness check of the kind Amazon's published ranks
    allowed, and pretending otherwise would put a fabricated number in the
    sidecar.

    `shown` is accepted so the family's shared signature holds.
    """
    return None


def search_header(html: str) -> Optional[str]:
    """The raw result-count header, for the sidecar. Worth recording, worth
    nothing as a count — see `total_results`."""
    soup = BeautifulSoup(html, "html.parser")
    node = soup.select_one(SELECTORS["search_info"])
    if node is None:
        return None
    return re.sub(r"\s{2,}", " ", node.get_text(" ", strip=True)) or None


def total_pages(html: str) -> Optional[int]:
    """No page count is published either — there is no pagination markup at
    all on search, and a category listing prints no last-page number."""
    return None


def parse_products(html: str, url: str, page: int = 1,
                   category: Optional[str] = None) -> List[Product]:
    """Every product in the grid, in the order the site laid them out.

    One path, not two: there is no structured data to prefer. See the module
    docstring.
    """
    soup = BeautifulSoup(html, "html.parser")
    kind, tiles = _tiles(soup, url)
    if not tiles:
        return []

    cat = category or category_from_url(url)
    host = site_host(url) or SOURCE_DEFAULT
    rows: List[Product] = []

    for position, tile in enumerate(tiles, start=1):
        path = product_path(tile.get("href"), url)
        if not path:
            continue
        text = _tile_text(tile)
        prices = prices_in(text)
        price = prices[0] if prices else None
        original = prices[1] if len(prices) > 1 else None
        sold, sold_is_floor = sold_in(text)
        alt = _tile_image_alt(tile)

        if kind == "search":
            shop, location = _tile_shop(tile)
        else:
            shop, location = _category_tile_shop(tile), None

        rows.append(Product(
            source=host,
            url=strip_tracking(urljoin(url, tile.get("href") or "")),
            sku=path,
            title=_title_of(tile, alt),
            brand=shop or path.split("/")[1],
            price=price,
            # A fact on this site, not a guess: one storefront, one currency,
            # measured identical from two exit countries. It still comes from
            # the symbol `Rp` rather than from structured data, which is why
            # `price_source` says "dom" and not more.
            currency=CURRENCY if price is not None else None,
            original_price=original,
            discount_pct=_discount_from(price, original),
            rating=rating_in(text),
            review_count=None,      # never on a tile; --mode product has it
            in_stock=None,          # never stated on a tile
            image_url=_tile_image(tile),
            category=cat,
            price_source="dom",
            page=page,
            position=position,
            shop_slug=path.split("/")[1],
            shop_location=location,
            sold=sold,
            sold_is_floor=sold_is_floor,
            slug_id=slug_tail_id(path),
        ))

    _report_coverage(rows, kind, url)
    return rows


# Below these shares something is wrong with the read rather than with the
# page, and a warning naming the number is what turned two silent regressions
# in this family into five-minute fixes. The thresholds differ by page kind
# because the pages genuinely differ: a category tile prints no rating and no
# was-price at all.
_COVERAGE_FLOORS = {
    "search":   {"price": 0.98, "title": 0.98, "rating": 0.95, "brand": 0.98},
    "category": {"price": 0.95, "title": 0.95, "brand": 0.90},
}


def _report_coverage(rows: Sequence[Product], kind: str, url: str) -> None:
    if not rows:
        return
    floors = _COVERAGE_FLOORS.get(kind, {})
    total = len(rows)
    for field, floor in floors.items():
        got = sum(1 for r in rows if getattr(r, field, None) is not None)
        share = got / total
        if share < floor:
            logger.warning(
                "%s coverage %.0f%% (%d/%d) on a %s page, below the %.0f%% "
                "this site normally gives — the markup may have changed: %s",
                field, share * 100, got, total, kind, floor * 100, url)
    imgs = sum(1 for r in rows if r.image_url)
    logger.info("parsed %d products from a %s page (%d with a loaded image; "
                "images below the fold are placeholders until scrolled)",
                total, kind, imgs)


# ---------------------------------------------------------------------------
# Detail pages: the Apollo cache
# ---------------------------------------------------------------------------
# A detail page carries no JSON-LD either, but it does carry a serialised
# Apollo cache in an inline script:
#
#     window.__cache = {"ROOT_QUERY":{…},"pdpBasicInfo103490518624":{…},…}
#
# That is structured data even though it is not schema.org, and it is the
# primary path for --mode product. What it holds, measured:
#
#     pdpBasicInfo<id>   productID, alias, shopID, shopName, url, condition,
#                        status, weight/weightUnit, minOrder/maxOrder,
#                        createdAt, category ->
#     pdpCategory<id>    name, breadcrumbURL
#     $pdpBasicInfo<id>.stats     rating, countReview
#     $pdpBasicInfo<id>.txStats   countSold (EXACT), itemSoldFmt
#
# The price is NOT in it — that comes from a meta tag, below.
_CACHE_RE = re.compile(r'window\.__cache\s*=\s*')


def _apollo_cache(html: str) -> Optional[dict]:
    """The page's Apollo cache as a dict, or None.

    Brace-matched rather than regexed to the end: the object is 67 KB of
    nested JSON with escaped quotes throughout, and a greedy pattern picks up
    whatever script follows it.
    """
    m = _CACHE_RE.search(html or "")
    if not m:
        return None
    start = m.end()
    if start >= len(html):
        return None
    if html[start] == '"':
        # Some builds emit it as a JSON string literal holding JSON.
        i = start + 1
        while i < len(html):
            if html[i] == "\\":
                i += 2
                continue
            if html[i] == '"':
                break
            i += 1
        try:
            return json.loads(json.loads(html[start:i + 1]))
        except (ValueError, TypeError):
            return None
    if html[start] != "{":
        return None
    depth, i, in_str, esc = 0, start, False, False
    while i < len(html):
        ch = html[i]
        if in_str:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                in_str = False
        elif ch == '"':
            in_str = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                break
        i += 1
    try:
        return json.loads(html[start:i + 1])
    except ValueError:
        return None


_BASIC_INFO_RE = re.compile(r'^pdpBasicInfo(\d+)$')


def _basic_info(cache: dict) -> Tuple[Optional[str], Optional[dict]]:
    for key, value in (cache or {}).items():
        m = _BASIC_INFO_RE.match(key)
        if m and isinstance(value, dict):
            return m.group(1), value
    return None, None


def _cache_ref(cache: dict, node, field: str) -> Optional[dict]:
    """Follow one Apollo reference — `{"type":"id","id":"pdpCategory2787"}`."""
    ref = (node or {}).get(field)
    if isinstance(ref, dict) and isinstance(ref.get("id"), str):
        target = cache.get(ref["id"])
        return target if isinstance(target, dict) else None
    return None


# The price, and the one thing on this page that looks like structured data
# and is not quite:
#
#     <meta property="product:price:amount"   content="7500">
#     <meta property="product:price:currency" content="Rp">
#
# 7500 matched the tile's `Rp7.500` exactly, so this is a genuine SECOND view
# of the price and is what makes `price_source` mean something in this mode.
#
# `Rp` is a SYMBOL, not an ISO 4217 code. §4's tier-2 rule is a written code
# checked against an allowlist of real codes; handing that allowlist the
# string "Rp" and asking what it thinks is how a size chart becomes a
# currency. It is mapped through a symbol table instead.
_SYMBOL_TO_ISO = {"rp": "IDR", "idr": "IDR"}


def _meta_content(soup, *names: str) -> Optional[str]:
    for name in names:
        for attr in ("property", "name", "itemprop"):
            node = soup.find("meta", attrs={attr: name})
            if node is not None and node.get("content"):
                return node["content"].strip()
    return None


def _to_int(value) -> Optional[int]:
    try:
        return int(str(value).strip())
    except (TypeError, ValueError):
        return None


def _to_float(value) -> Optional[float]:
    try:
        return float(str(value).strip().replace(",", "."))
    except (TypeError, ValueError):
        return None


# The detail page's title, and this one is worth spelling out because three
# of the four obvious sources are wrong:
#
#   <h1>                       "Kopi Hitam Bubuk Robusta …"                 exact
#   lblPDPProductNameJumper    the same string                              exact
#   og:title / twitter:title   "Promo Kopi Hitam … di Zayn Snack | Tokopedia"
#   <title>                    "Promo Kopi Hitam … - Kab. Magetan - Zayn Snack | Tokopedia"
#
# The meta tags carry a "Promo " prefix the product's name does not have and
# a " di {shop} | Tokopedia" suffix, and stripping those with a regex is
# guesswork about a marketing string. The `<h1>` is the product name as the
# page renders it, and the site's own test hook agrees with it byte for byte.
_TITLE_JUMPER = '[data-testid="lblPDPProductNameJumper"]'
_TITLE_META_PREFIX = re.compile(r'^(?:Promo|Jual)\s+(?=\S)')


def _detail_title(soup, shop_name: Optional[str]) -> Optional[str]:
    for selector in (_TITLE_JUMPER, "h1"):
        node = soup.select_one(selector)
        if node is not None:
            text = node.get_text(" ", strip=True)
            if text:
                return text
    # Last resort: the meta title with its two decorations removed. Only
    # reached if the page rendered no h1 at all, which no capture has done.
    raw = (_meta_content(soup, "og:title", "twitter:title") or "").strip()
    if not raw:
        return None
    raw = _TITLE_META_PREFIX.sub("", raw)
    raw = re.sub(r'\s*\|\s*Tokopedia\s*$', "", raw)
    if shop_name:
        raw = re.sub(r'\s+di\s+' + re.escape(shop_name) + r'\s*$', "", raw)
    return raw.strip() or None


# The seller's city on a detail page, which only the `<title>` states:
#
#     "Promo {product} - Kab. Magetan - Zayn Snack | Tokopedia"
#
# Split on the shop name we already have from the Apollo cache rather than on
# position, so a product name containing " - " cannot shift the answer, and
# return None unless the shape is exactly right. A guessed city is worse than
# no city (§8).
def _detail_shop_location(soup, shop_name: Optional[str]) -> Optional[str]:
    if not shop_name or soup.title is None:
        return None
    raw = (soup.title.string or "").strip()
    marker = " - " + shop_name
    if not raw.endswith(marker + " | Tokopedia"):
        return None
    head = raw[:-len(marker + " | Tokopedia")]
    _, sep, city = head.rpartition(" - ")
    if not sep or not city.strip() or len(city) > 60:
        return None
    return city.strip()


def parse_product_page(html: str, url: str,
                       category: Optional[str] = None) -> Optional[Product]:
    """One product from its own page: Apollo cache first, meta tags for price.

    Returns None when the page is not a product page — which is a real case
    and not a fault: a shop front and a hub both answer 200 and neither has a
    `pdpBasicInfo` node.
    """
    soup = BeautifulSoup(html or "", "html.parser")
    cache = _apollo_cache(html) or {}
    product_id, basic = _basic_info(cache)

    price = _to_float(_meta_content(soup, "product:price:amount"))
    raw_currency = _meta_content(soup, "product:price:currency")
    currency = _SYMBOL_TO_ISO.get((raw_currency or "").strip().lower())
    if price is not None and currency is None:
        # The page stated a price without a currency this table knows. Never
        # default it (§8): say nothing rather than claim IDR.
        logger.warning("unrecognised currency %r on %s — leaving it null",
                       raw_currency, url)

    canonical = soup.select_one('link[rel="canonical"]')
    row_url = strip_tracking(
        (basic or {}).get("url")
        or (canonical.get("href") if canonical is not None else None)
        or url)

    if basic is None and price is None:
        return None

    stats = _cache_ref(cache, basic, "stats") or {}
    tx_stats = _cache_ref(cache, basic, "txStats") or {}
    cat_node = _cache_ref(cache, basic, "category") or {}

    sold = _to_int(tx_stats.get("countSold"))
    status = (basic or {}).get("status")
    max_order = _to_int((basic or {}).get("maxOrder"))
    in_stock = None
    if status:
        in_stock = status == "ACTIVE" and (max_order is None or max_order > 0)

    shop_name = (basic or {}).get("shopName") or None
    title = _detail_title(soup, shop_name)

    path = product_path(row_url) or product_path(url)
    return Product(
        source=site_host(row_url) or SOURCE_DEFAULT,
        url=row_url,
        sku=path,
        title=title,
        brand=(basic or {}).get("shopName") or (path.split("/")[1] if path else None),
        price=price,
        currency=currency if price is not None else None,
        # A detail page carries no strikethrough of its own, and the "similar
        # products" carousel's prices belong to other products (§4). Null
        # rather than a neighbour's number.
        original_price=None,
        discount_pct=None,
        rating=_to_float(stats.get("rating")),
        review_count=_to_int(stats.get("countReview")),
        in_stock=in_stock,
        image_url=(basic or {}).get("defaultMediaURL") or None,
        category=cat_node.get("name") or category or None,
        # The price came from a meta tag and the rest from the page's own
        # Apollo cache. Named for what it is rather than borrowing the
        # family's "jsonld" label for something that is not JSON-LD.
        price_source="meta+apollo" if basic else "meta",
        page=None,
        position=None,
        shop_slug=path.split("/")[1] if path else None,
        shop_location=_detail_shop_location(soup, shop_name),
        # EXACT here, where a tile's is a floor — 207785 against the tile's
        # "100rb+" for the same product. The two are not comparable and
        # `sold_is_floor` is what says so.
        sold=sold,
        sold_is_floor=False if sold is not None else None,
        slug_id=slug_tail_id(row_url),
        product_id=product_id,
        shop_id=(basic or {}).get("shopID") or None,
        condition=((basic or {}).get("condition") or "").title() or None,
        weight_grams=_weight_grams(basic),
        stock_max=max_order,
        listed_at=(basic or {}).get("createdAt") or None,
        category_url=strip_tracking(cat_node.get("breadcrumbURL") or "") or None,
    )


_WEIGHT_TO_GRAMS = {"GRAM": 1, "GRAMS": 1, "KILOGRAM": 1000, "KG": 1000}


def _weight_grams(basic: Optional[dict]) -> Optional[int]:
    """The shipping weight in grams, so one column holds one unit.

    The site states a number and a unit separately (`weight: 1`,
    `weightUnit: "KILOGRAM"`), and a column mixing grams with kilograms would
    be a number nobody can compare.
    """
    if not basic:
        return None
    value = _to_float(basic.get("weight"))
    unit = str(basic.get("weightUnit") or "").upper()
    if value is None or unit not in _WEIGHT_TO_GRAMS:
        return None
    return int(round(value * _WEIGHT_TO_GRAMS[unit]))


def shop_metadata(html: str, url: str) -> Dict[str, Optional[str]]:
    """The seller's own facts, for the sidecar of a run that covers one shop.

    Read from the same Apollo cache. A run covers exactly one shop, so these
    would produce an output file holding a single line if they were a row —
    and they cannot be attached to a product row without claiming they
    describe the product.
    """
    cache = _apollo_cache(html) or {}
    _, basic = _basic_info(cache)
    if not basic:
        return {}
    return {
        "shop_id": basic.get("shopID") or None,
        "shop_name": basic.get("shopName") or None,
        "shop_slug": shop_from_url(url),
    }
