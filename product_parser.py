def _grid_of(soup, kind: str):
    if kind == "search":
        return soup.select_one(SELECTORS["search_grid"])
    if kind == "category":
        return soup.select_one(SELECTORS["category_grid"])
    # An unknown URL shape: try both, search first.
    return (soup.select_one(SELECTORS["search_grid"])
            or soup.select_one(SELECTORS["category_grid"]))


def _tiles(soup, url: str) -> Tuple[str, List]:
    """(page kind actually found, the tiles) — grid-scoped, always.

    Scoping is not a nicety here. `/p/<slug>` hubs and the "cheaper
    products" carousel that appears on every category page both hold product
    links: page 1 and page 2 of one category shared exactly 3 products, and
    all three were that carousel. Document-wide anchor collection would
    report them as real rows on both pages.
    """
    kind = listing_kind(url)
    grid = _grid_of(soup, kind)
    if grid is None:
        return "none", []

    search_tiles = [
        a for a in grid.select("a[href]")
        if product_path(a.get("href"), url)
        and a.select_one(SELECTORS["search_tile_marker"]) is not None
    ]
    if search_tiles:
        return "search", search_tiles

    cat_tiles = [
        a for a in grid.select(SELECTORS["category_anchor"])
        if product_path(a.get("href"), url)
        and a.select_one(SELECTORS["category_tile_marker"]) is not None
    ]
    if cat_tiles:
        return "category", cat_tiles
    return "none", []


def _count_tiles(soup, url: str) -> int:
    return len(_tiles(soup, url)[1])


def _without_image_block(tile):
    """A copy of the tile with the image container and its overlays removed.

    The discount badge and the "PreOrder" label are siblings of the image
    wrapper, so they sit BEFORE the title in reading order:

        94% Kopi Hitam Bubuk Robusta … Rp7.500 Rp120.000 …

    Stripping a leading percentage from the text would work on those and
    destroy a title that legitimately begins with one. Removing the image
    container structurally cannot: `imgLeg-c` is the site's own attribute and
    its parent is exactly the overlay group. Verified to leave a usable title
    on all 95 tiles of two captures, and to remove `45% PreOrder` from the
    two tiles that carry it.
    """
    clone = copy.copy(tile)
    marker = clone.select_one(SELECTORS["search_tile_marker"])
    if marker is not None and marker.parent is not None:
        marker.parent.decompose()
    return clone


def _title_of(tile, image_alt: Optional[str]) -> Optional[str]:
    """The product title: everything before the first price.

    Text-order rather than a selector, because the selector this would use
    (`span.+tnoqZhn89+NHUA43BpiJg==`) is a build hash and its predecessor
    (`data-testid="linkProductName"`) has already been deleted once. Reading
    order has outlived both.

    The image `alt` is the title verbatim on a category tile — checked
    against all 60, zero mismatches — so it is the cross-check and the
    fallback rather than the source.
    """
    body = _tile_text(_without_image_block(tile))
    head = re.split(r'Rp\s*\d', body, maxsplit=1)[0].strip(" -|·")
    if head and len(head) <= 300:
        return head
    if image_alt and image_alt != "product-image":
        return image_alt.strip() or None
    return head or None


# Images are the trap on this page, twice over, and both halves are the §10
# lesson: a column can be 100% populated and entirely wrong.
#
# **A tile holds several images and only one of them is the product.** A
# search tile carries 3 to 7 `<img>`: the product, a rating star, a "three
# dots" glyph, usually a shop badge, sometimes a "Beli Lokal" ribbon and a
# video thumbnail. Taking the first one that happens to sit on the site's CDN
# returns the SHOP BADGE for most rows — a populated column of
# `Power Merchant Pro.png`.
#
# **And the product image is lazy-loaded.** The browser fetches only what it
# has painted, so a tile below the fold carries a placeholder: 55 of 95
# search tiles held an SVG under `/obj/tokopedia-web-sg/zeus_v2/`, and 30 of
# 60 category tiles held a `data:` URI.
#
# So the product image is recognised POSITIVELY, by three things at once —
# it is the tile's own product `<img>`, it sits on the site's image CDN, and
# its path carries the `~tplv-` transform marker that every real product
# image has and no icon does. Everything else is null, which makes
# `image_url` honestly sparse rather than dishonestly complete: scroll
# further and more rows fill in.
_IMAGE_HOST_RE = re.compile(
    r'^https?://[^/]*(?:tokopedia-static\.net|images\.tokopedia\.net)/', re.I)
# Icons and chrome live under these path segments; product images never do.
_IMAGE_CHROME_RE = re.compile(r'/(?:obj|img)/', re.I)
# The CDN's image-transform marker, e.g.
# `…/ed86f8de…~tplv-aphluv4xwc-resize-jpeg:700:0.jpeg`.
_IMAGE_TRANSFORM_RE = re.compile(r'~tplv-', re.I)


def _product_img(tile):
    """The tile's product `<img>`, told apart from its icons.

    A search tile labels it `alt="product-image"` (95 of 95). A category tile
    does not label it at all — its `alt` IS the product title — but it holds
    exactly two images, the product first and the shop badge second, on all
    60 measured.
    """
    labelled = tile.select_one(SELECTORS["product_image"])
    if labelled is not None:
        return labelled
    imgs = tile.select("img")
    return imgs[0] if imgs else None


def _tile_image(tile) -> Optional[str]:
    img = _product_img(tile)
    if img is None:
        return None
    if img.get("data-li-lazy") is not None:
        return None           # the site's own "not loaded yet" marker
    src = (img.get("src") or "").strip()
    if not src or not _IMAGE_HOST_RE.match(src):
        return None
    if _IMAGE_CHROME_RE.search(src) or not _IMAGE_TRANSFORM_RE.search(src):
        return None
    return src


def _tile_image_alt(tile) -> Optional[str]:
    img = tile.select_one(SELECTORS["product_image"]) or tile.select_one("img[alt]")
    return img.get("alt") if img is not None else None


def _tile_shop(tile) -> Tuple[Optional[str], Optional[str]]:
    """(shop name, shop city) from the tile's two `span.flip` nodes.

    Exactly two per search tile, 190 across 95 tiles with no exceptions, in
    that order. A category tile has neither reliably, so both come back None
    there and the shop name falls back to the slug in the URL — which is the
    same seller by definition, just less pretty.
    """
    spans = [s.get_text(" ", strip=True) for s in
             tile.select(SELECTORS["shop_and_location"])]
    spans = [s for s in spans if s]
    if len(spans) >= 2:
        return spans[0], spans[1]
    if len(spans) == 1:
        return spans[0], None
    return None, None


def _category_tile_shop(tile) -> Optional[str]:
    """A category tile's shop name, from the badge image's `alt`.

    The shop badge's `alt` is the shop name — checked on all 60 tiles. Not
    the product image's, which is the product title, so the two have to be
    told apart by which one is NOT the title.
    """
    imgs = tile.select("img[alt]")
    if len(imgs) < 2:
        return None
    alt = (imgs[-1].get("alt") or "").strip()
    return alt or None


