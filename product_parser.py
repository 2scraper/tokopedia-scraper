# ---------------------------------------------------------------------------
# Prices
# ---------------------------------------------------------------------------
# IDR as Tokopedia writes it: "Rp7.500". Dot grouping, and **no minor unit in
# any of the 74 distinct prices** across the captures — not one comma.
#
# So this is the `1.234,56` convention with the decimals absent, and the
# family's "exactly three trailing digits means a thousands grouping" rule
# gives the right answer on every price seen (Rp7.500 → 7500, Rp1.800 →
# 1800, Rp180.800 → 180800). The comma branch is kept anyway: it costs
# nothing, and "no IDR price has cents" is a claim these six captures do not
# license.
_GROUP_SPACES = "    "   # NBSP, narrow NBSP, thin space, space
_AMOUNT = (r'\d{1,3}(?:[.' + _GROUP_SPACES + r']\d{3})+(?:,\d{1,2})?'
           r'|\d+(?:,\d{1,2})?')
_PRICE_RE = re.compile(r'Rp\s*(' + _AMOUNT + r')')

# Things that live INSIDE a tile and carry their own number, which is
# MediaMarkt's instalment line (§4) in a different costume:
#
#   "Hemat s.d  8% Pakai Bonus"   29 of 95 search tiles — a promo, not the
#                                 discount, and its percentage is not the
#                                 badge's
#   "Tambah ke Wishlist"          the label of a button inside the category
#                                 anchor; lands in the title if not removed
#
# Both are stripped from the tile's text before anything is read out of it.
_PROMO_RE = re.compile(r'Hemat\s+s\.?d\.?\s*[\d.,]+\s*%[^0-9]*', re.I)
_WISHLIST_RE = re.compile(r'Tambah ke Wishlist', re.I)
# Percentages come out before prices are matched, not after. A rejected match
# has still consumed the currency symbol, so filtering afterwards loses the
# real price too (§4).
_PCT_RE = re.compile(r'-?\s*\d{1,3}(?:[.,]\d+)?\s*%')


def _normalize_amount(raw: str) -> Optional[float]:
    """Turn a written amount into a number, honouring all three groupings.

    `1,234.56` · `1.234,56` · `1 234,56`, with the space form allowing NBSP,
    narrow NBSP and thin space — a rendered page uses a no-break variant so
    the number does not wrap, and missing them parses `1 234` as 234.
    """
    s = raw.strip()
    for sp in _GROUP_SPACES:
        if sp != " ":
            s = s.replace(sp, " ")
    s = s.replace(" ", ".")
    has_dot, has_comma = "." in s, "," in s
    if has_dot and has_comma:
        # Whichever separator comes LAST is the decimal point.
        dec = "," if s.rfind(",") > s.rfind(".") else "."
        s = s.replace("." if dec == "," else ",", "").replace(dec, ".")
    elif has_comma:
        head, _, tail = s.rpartition(",")
        # Exactly three trailing digits is a thousands grouping: no currency
        # has a three-digit subunit, so "1,234" is 1234.
        s = (head + tail) if len(tail) == 3 else s.replace(",", ".")
    elif has_dot:
        head, _, tail = s.rpartition(".")
        if len(tail) == 3:
            s = s.replace(".", "")
        # One dot with 1-2 trailing digits would be a decimal point, and is
        # left as such. No Tokopedia price has ever been seen written that
        # way; if one is, this reads it correctly rather than multiplying it
        # by a thousand.
    try:
        return float(s)
    except ValueError:
        return None


def _tile_text(node) -> str:
    """The tile's readable text with the known in-tile noise removed."""
    text = node.get_text(" ", strip=True)
    text = _WISHLIST_RE.sub(" ", text)
    text = _PROMO_RE.sub(" ", text)
    return re.sub(r"\s{2,}", " ", text).strip()


def prices_in(text: str) -> List[float]:
    """Every `Rp` amount in reading order, percentages removed first."""
    out: List[float] = []
    for m in _PRICE_RE.finditer(_PCT_RE.sub(" ", text)):
        val = _normalize_amount(m.group(1))
        if val is not None:
            out.append(val)
    return out


def _discount_from(price: Optional[float],
                   original_price: Optional[float]) -> Optional[float]:
    """The discount COMPUTED from the two prices, never read off the badge.

    Two reasons, both measured. Tokopedia prints the badge only above some
    threshold: two search tiles carry a strike price at 7% and 8% off with no
    badge at all, so computing recovers 88 of 95 rows where reading the badge
    recovers 86. And where both exist they agree — 0 mismatches over 1
    percentage point across all 86 — so there is nothing to be gained by
    trusting the printed one.

    None rather than 0 or a negative when the figures are not what they were
    taken for, so a canary can assert "no original_price at or below its
    price" and mean it.
    """
    if price is None or original_price is None:
        return None
    if original_price <= 0 or original_price <= price:
        return None
    return round((original_price - price) / original_price * 100, 2)


# ---------------------------------------------------------------------------
# Rating and the sold count
# ---------------------------------------------------------------------------
# The tile prints "4.7  100rb+ terjual" — the rating, then the number sold.
# `rb` is *ribu* (thousand), `jt` is *juta* (million), and the trailing `+`
# means the site has rounded DOWN: "100rb+" against a detail page's exact
# `countSold` of 207785 for the same product. So a listing-mode sold count is
# a floor and says so in its own column; the two modes' values are not
# comparable and `diff_runs.py` must not be handed both.
_SOLD_UNITS = {None: 1, "": 1, "rb": 1_000, "jt": 1_000_000}
_SOLD_RE = re.compile(r'([\d.,]+)\s*(rb|jt)?\s*(\+?)\s*terjual', re.I)

# The rating is matched only where a sold count FOLLOWS it, and that lookahead
# is load-bearing rather than tidy. A product with no reviews prints no
# rating, and then its sold count stands alone:
#
#     "KOPI SAIYO : 100% Robusta Rp30.000 5 terjual Galeri UMKM …"
#
# A looser pattern reads that 5 as a five-star rating on a product that has
# never been rated. One such tile in 190.
_RATING_RE = re.compile(
    r'(?<![\d.,])([0-5](?:[.,]\d)?)\s+(?=[\d.,]+\s*(?:rb|jt)?\+?\s*terjual)',
    re.I)


def rating_in(text: str) -> Optional[float]:
    m = _RATING_RE.search(text)
    if not m:
        return None
    try:
        return float(m.group(1).replace(",", "."))
    except ValueError:
        return None


def sold_in(text: str) -> Tuple[Optional[int], Optional[bool]]:
    """(units sold, whether that figure is a floor). (None, None) if absent."""
    m = _SOLD_RE.search(text)
    if not m:
        return None, None
    n = _normalize_amount(m.group(1))
    if n is None:
        return None, None
    unit = (m.group(2) or "").lower() or None
    is_floor = bool(m.group(2)) or m.group(3) == "+"
    return int(n * _SOLD_UNITS[unit]), is_floor


# ---------------------------------------------------------------------------
# URLs, ids and pagination
# ---------------------------------------------------------------------------
# A product lives at /{shop-slug}/{product-slug}. Most product slugs end in a
# 19-digit tail and it is TEMPTING to make that the sku — but it is not the
# product id and it is not always there.
#
#   * The real id is `pdpBasicInfo.productID` in a detail page's Apollo cache:
#     103490518624 for a product whose URL tail is 1731177319241910164.
#   * 4 of 40 listing URLs carry no tail at all, and two of those carry a
#     short hex suffix instead (`-c69d`, `-71e1e`). All four are ordinary
#     organic products with byte-identical tile markup.
#
# So `sku` is the URL PATH — always present, stable, and what the site's own
# canonical uses. The numeric id, where a detail page states it, goes in its
# own column.
_PRODUCT_PATH_RE = re.compile(r'^/(?P<shop>[^/?#]+)/(?P<slug>[^/?#]+)$')
_SLUG_TAIL_RE = re.compile(r'-(\d{15,22})$')

# First path segments that are Tokopedia's own routes rather than a shop.
# A two-segment path under any of these is not a product, and letting one
# through is how a junk link steals a real product's row (§4).
_NOT_A_SHOP = frozenset("""
    search p find discovery promo help about register login deals now mall c
    blog career affiliate mitra seller review order cart checkout wishlist
    official-store rewards play flight kereta-api events pesan-antar
    tokopedia-care contact-us privacy terms bantuan how-to-shop
    """.split())

# Query parameters that identify the visit rather than the page. Stripped
# before a URL becomes a row's `url` or is compared to a canonical, because a
# detail page's own canonical arrives with a UTM tail
# (?utm_source=google&utm_medium=organic&utm_campaign=pdp) and a listing
# anchor arrives with an extParam carrying the search id — so two views of
# one product never join unless both sides are cleaned.
TRACKING_PARAMS = frozenset("""
    extParam utm_source utm_medium utm_campaign utm_term utm_content
    src search_id keyword whid aff_unique_id trkid ref refer
    navsource srp_component_id srp_page_id srp_page_title
    """.split())


def strip_tracking(url: str) -> str:
    parts = urlsplit(url)
    kept = [(k, v) for k, v in parse_qsl(parts.query, keep_blank_values=True)
            if k not in TRACKING_PARAMS]
    return urlunsplit((parts.scheme, parts.netloc, parts.path,
                       urlencode(kept), ""))


def product_path(href: str, base_url: str = "") -> Optional[str]:
    """The `/{shop}/{slug}` path of a product link, or None if it is not one."""
    if not href:
        return None
    absolute = urljoin(base_url or "https://www.tokopedia.com/", href)
    parts = urlsplit(absolute)
    host = (parts.hostname or "").lower()
    if host and host not in HOSTS:
        return None
    path = parts.path.rstrip("/")
    m = _PRODUCT_PATH_RE.match(path)
    if not m or m.group("shop").lower() in _NOT_A_SHOP:
        return None
    return path


def sku_from_url(url: str) -> Optional[str]:
    return product_path(url)


def shop_from_url(url: str) -> Optional[str]:
    path = product_path(url)
    return path.split("/")[1] if path else None


def slug_tail_id(url: str) -> Optional[str]:
    """The 19-digit tail on a product slug, where there is one.

    NOT the product id — see the note above `_PRODUCT_PATH_RE`. Exposed
    because it is a real identifier the site puts in its own URLs, and
    because naming it makes it harder for a future edit to mistake it for
    `product_id`.
    """
    path = product_path(url)
    if not path:
        return None
    m = _SLUG_TAIL_RE.search(path)
    return m.group(1) if m else None


_SEARCH_PATHS = ("/search",)
_CATEGORY_PREFIX = "/p/"


def listing_kind(url: str) -> str:
    """"search" · "category" · "hub" · "product" · "unknown"."""
    path = urlsplit(url).path.rstrip("/") or "/"
    if any(path == p or path.startswith(p + "/") for p in _SEARCH_PATHS):
        return "search"
    if path.startswith(_CATEGORY_PREFIX):
        segments = [s for s in path[len(_CATEGORY_PREFIX):].split("/") if s]
        # One segment is a discovery hub with no grid on it; two or more is a
        # real listing. Measured: /p/makanan-minuman has 0 tiles,
        # /p/makanan-minuman/minuman/kopi-bubuk has 65.
        return "category" if len(segments) >= 2 else "hub"
    if product_path(path):
        return "product"
    return "unknown"


# Category listings paginate with `?page=N`. Search does NOT, and the
# difference is the whole reason this is a function rather than a constant —
# two page kinds on one site using different conventions is amazon-scraper's
# `?page=` versus `?pg=` all over again.
PAGE_PARAM = "page"
PAGINATED_KINDS = ("category",)


def paginates_by_url(url: str) -> bool:
    """Whether page N of this listing has an address of its own.

    False for search, and that is measured rather than assumed. A fully
    scrolled search page publishes **no** `href` containing `page=`, no
    `link[rel=next]`, and no next-page button — every button on it is a
    filter or a sort. And appending `?page=2` does not paginate, it EMPTIES
    the result set: the page comes back with `Oops, produk nggak ditemukan`
    ("product not found"), no grid and no prices.

    That last part is the dangerous one. A `page_url()` that built `?page=N`
    unconditionally would fetch that empty page, find no new sku, conclude
    the listing was exhausted, and report a COMPLETE run holding page 1 —
    the silent-single-page failure of §7 arriving by a different route. So
    the engines must ask this before they plan page URLs.
    """
    return listing_kind(url) in PAGINATED_KINDS


def page_url(url: str, page_num: int) -> Optional[str]:
    """The address of page `page_num`, or None if the listing has none.

    Replaces an existing `page` rather than appending a second one, and
    preserves every other query parameter — the filters and the sort are
    what make a listing worth paginating.
    """
    if page_num <= 1:
        return strip_tracking(url)
    if not paginates_by_url(url):
        return None
    parts = urlsplit(strip_tracking(url))
    params = [(k, v) for k, v in parse_qsl(parts.query, keep_blank_values=True)
              if k != PAGE_PARAM]
    params.append((PAGE_PARAM, str(page_num)))
    return urlunsplit((parts.scheme, parts.netloc, parts.path,
                       urlencode(params), parts.fragment))


def page_number_from_url(url: str) -> int:
    for k, v in parse_qsl(urlsplit(url).query):
        if k == PAGE_PARAM:
            try:
                return max(1, int(v))
            except ValueError:
                return 1
    return 1


# ---------------------------------------------------------------------------
# Category
# ---------------------------------------------------------------------------
# A category comes from the URL on a category listing, and from the detail
# page's own breadcrumb otherwise — which is better than either, because it is
# the site's own classification rather than our reading of a path.
_NOT_A_CATEGORY = frozenset("""
    p search find discovery promo deals now mall
    """.split())


def category_from_url(url: str) -> Optional[str]:
    """The category slug a listing URL names, or None."""
    path = urlsplit(url).path.rstrip("/")
    if not path.startswith(_CATEGORY_PREFIX):
        return None
    segments = [s for s in path[len(_CATEGORY_PREFIX):].split("/")
                if s and s not in _NOT_A_CATEGORY]
    return "/".join(segments) or None


# ---------------------------------------------------------------------------
# Page state: served, refused, empty
# ---------------------------------------------------------------------------
# **This site gives a refusal no content to detect.** Every other site in
# this family answers a request it does not like with something — an Akamai
# reference, a DataDome shell, a branded error page under 403. Tokopedia, to
# an address it has scored badly, accepts the connection, completes TLS,
# opens the HTTP/2 stream and then resets it. Nothing arrives. curl reports
# exit 92, Chromium reports ERR_HTTP2_PROTOCOL_ERROR, and there is no page.
#
# So detection here is inverted: rather than looking for a marker a block
# page carries, look for a marker every REAL page carries and treat its
# absence as the signal. That is §8's `assets.mmsrg.com` trick, and
# Tokopedia's equivalent is its own asset host — present 3+ times on every
# one of the six captures, on every page kind, including the empty-result
# page.
_ASSET_MARKER = re.compile(r'tokopedia-static\.net|images\.tokopedia\.net', re.I)
_ASSET_MIN_MATCHES = 2

# Vendor challenge markers. Kept SHORT on purpose: none of these has ever
# been observed on this site, and every one that has not is a guess. The list
# exists because a bot manager can be switched on between deploys and a
# scraper that cannot name what stopped it is much harder to fix.
#
# Deliberately NOT included: `cf-turnstile`. The 2Captcha Scraping Browser's
# auto-solve extension injects a `cf-turnstile` hunter into every page it
# loads, so the marker appears on perfectly good pages fetched over
# --cdp-endpoint (§8). Adding it would need the extension-tag filter below
# to be exercised, and adding a marker whose only observed source is our own
# extension is how dead code spreads. The filter is applied anyway, so a
# future edit that broadens this list is already protected.
# Deliberately NOT included: the bare string "akamai". Tokopedia is fronted
# by Akamai, so its own performance-monitoring script references
# `…clientnsv4-s.akamaihd.net` on EVERY page — a live run of a /p/<slug> hub
# reported "Blocked by akamai" and exit 3 on a 191 KB page the site had
# plainly served. A marker that matches every page of the site it is meant to
# guard is worse than no marker. Akamai's actual REFUSAL strings are the two
# below, and those do not appear on a served page.
BOT_CHALLENGE_MARKERS = (
    "Request unsuccessful",       # Akamai's own refusal page
    "Reference #",                # ...and its reference line
    "g-recaptcha",
    "recaptcha/api.js",           # the loader
    "recaptcha/api2/anchor",      # a RENDERED widget's iframe
    "recaptcha/api2/bframe",      # ...and its challenge frame
    "data-sitekey",               # any vendor's widget, configured in markup
    "hcaptcha.com",
    "px-captcha",
    "_Incapsula_Resource",
)

# THE SITE'S OWN CAPTCHA MOUNT POINT, and it needs a structural check rather
# than a marker.
#
# Tokopedia ships `<captcha-widgets></captcha-widgets>` on EVERY page it
# serves — 13 of 13 dumps, including the empty-result page and a discovery
# hub — and its front-end config carries a reCAPTCHA sitekey
# (`"CAPTCHA_SITE_KEY":"6L…"`). So the machinery is present and configured
# everywhere, and NOTHING was ever rendered into it: no challenge of any kind
# appeared on any capture or any live run.
#
# That makes the bare tag useless as a marker — matching it would report a
# challenge on every page, which is the mistake the bare string "akamai"
# already made here once. What IS a signal is the element having CONTENT.
_WIDGET_MOUNT_RE = re.compile(
    r'<captcha-widgets\b[^>]*>(?P<body>.*?)</captcha-widgets\s*>',
    re.I | re.S)


def captcha_widget_is_populated(html: str) -> bool:
    """Whether the site's own `<captcha-widgets>` mount point has anything in it.

    Empty on every page Tokopedia has ever been observed serving. If it ever
    has children, the site has rendered a challenge into it — and that is
    worth knowing even when the child carries none of the vendor markers
    above, which a bare `data-sitekey` div would not.
    """
    for m in _WIDGET_MOUNT_RE.finditer(html or ""):
        if m.group("body").strip():
            return True
    return False

_EXTENSION_TAG_RE = re.compile(
    r'<script\b[^>]*\bsrc\s*=\s*["\'](?:chrome|moz)-extension://[^"\']*["\'][^>]*>'
    r'(?:\s*</script>)?', re.I)


def _strip_extension_tags(html: str) -> str:
    """Remove browser-extension script tags before looking for markers.

    The Scraping Browser API ships an auto-solve extension that injects its
    own captcha hunters into every page. Its markup mentions the vendors it
    hunts, so a marker scan over the raw HTML can report a challenge on a
    1.8 MB page holding the full catalogue — which is exactly what happened
    on mediamarkt-scraper's first live run.
    """
    return _EXTENSION_TAG_RE.sub(" ", html)


# The empty-result page, which is a SUCCESS and not a block: Tokopedia
# answers 200 with its filter rail, its footer and this sentence where the
# grid would be. Seen on `?page=2` of a search URL and on any query with no
# matches.
_NO_RESULTS_MARKERS = (
    "produk nggak ditemukan",
    "produk tidak ditemukan",
    "Coba kata kunci lain",
)


def detect_bot_challenge(html: str, url: str = "") -> Optional[str]:
    """The name of a challenge vendor found in the markup, or None.

    Broad on purpose (§8): different geos and different scenarios surface
    different challenges, and a detection is only a warning unless the page
    also has no products on it.
    """
    if not html:
        return None
    cleaned = _strip_extension_tags(html)
    lowered = cleaned.lower()
    for marker in BOT_CHALLENGE_MARKERS:
        if marker.lower() in lowered:
            return marker
    # The site's own mount point, checked structurally rather than as a
    # substring — see `captcha_widget_is_populated`.
    if captcha_widget_is_populated(cleaned):
        return "captcha-widgets"
    return None


def served_by_tokopedia(html: str) -> bool:
    """Whether this markup is a page Tokopedia itself built.

    A served page is assembled out of the site's own assets; an interstitial
    is not. Measured over all six captures: 2 or more matches on every real
    page including the empty-result one.
    """
    if not html:
        return False
    return len(_ASSET_MARKER.findall(html)) >= _ASSET_MIN_MATCHES


def is_no_results(html: str) -> bool:
    return any(m.lower() in html.lower() for m in _NO_RESULTS_MARKERS)


def detect_page_state(html: str, status: Optional[int] = None,
                      url: str = "") -> str:
    """One of "content" · "empty" · "blocked" · "challenge" · "unknown".

    The engines must not each re-derive this: three copies of the triage
    across three engines drift, and the drift is silent — one engine
    reporting exit 3 where its twin reports exit 0 on the same page. The
    retry/solve/blocked decision that follows from this verdict lives in
    `page_flow.STATE_POLICY` as data.
    """
    if status is not None and status != 200:
        # A non-200 from this host is a refusal; it has never been observed
        # carrying a page worth parsing.
        return "blocked"
    if not html or not html.strip():
        return "blocked"
    # THE NO-RESULTS SENTENCE COMES FIRST, before the asset threshold, and
    # the ordering is the point. "Oops, produk nggak ditemukan" is the
    # site's OWN Indonesian copy — an unambiguous positive signal that
    # Tokopedia both served this page and has nothing to put on it — while
    # `served_by_tokopedia` is a heuristic with a threshold. Checked the
    # other way round, a minimal real page carrying one asset reference
    # instead of the measured 3-7 was reported as BLOCKED, which is exit 3
    # for a correct answer and sends the reader hunting for a proxy problem.
    if is_no_results(html):
        return "empty"
    if not served_by_tokopedia(html):
        # No asset-host references at all: whatever this is, Tokopedia did
        # not build it.
        return "blocked"
    challenge = detect_bot_challenge(html, url)
    soup = BeautifulSoup(html, "html.parser")
    if _grid_of(soup, listing_kind(url)) is not None and _count_tiles(soup, url):
        return "content"
    if listing_kind(url) == "product":
        # A detail page has no grid; what it has is a product. Treat the
        # page's own product markup as the content signal, so an engine in
        # --mode product is not told "unknown" about a page it parsed fine.
        if _apollo_cache(html) or _meta_content(soup, "product:price:amount"):
            return "content"
    if listing_kind(url) == "hub":
        # A `/p/<slug>` discovery hub. It answers 200 with banners and
        # recommendation carousels and has no grid on it, so there is nothing
        # to parse and nothing wrong — "empty" rather than "unknown", so the
        # engines report exit 4 instead of retrying a page that will never
        # have products on it.
        return "empty"
    if challenge:
        return "challenge"
    return "unknown"


