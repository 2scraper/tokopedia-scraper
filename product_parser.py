# ---------------------------------------------------------------------------
# Hosts
# ---------------------------------------------------------------------------
# Tokopedia is ONE storefront. Measured 2026-09-10 by fetching the same search
# URL through an Indonesian exit and a US exit: identical status, identical
# tile count, `<html lang="id">` both times, IDR prices both times, ship-to
# "Jakarta Pusat" both times, and **zero** price differences across the 68
# products both runs saw. There is no geo-redirect, no locale path prefix and
# no second currency.
#
# Which is why this repo has NO --country flag: there would be nothing for it
# to select, and a flag that can only disagree with the URL is worse than no
# flag. The `country-` segment of a Scraping Browser endpoint still matters
# for getting IN — see the README's access section — but not for what comes
# back.
HOSTS = ("tokopedia.com", "www.tokopedia.com")

# Hosts that look like they belong and do not. Refuse them WITH THE REASON:
# "is not a Tokopedia site" would be false for a Tokopedia subdomain that
# simply is not a storefront, and sends the reader hunting for a typo (§5).
UNSUPPORTED: Dict[str, str] = {
    "seller.tokopedia.com": "is Tokopedia's seller dashboard, which requires "
                            "a login and publishes no product pages",
    "gql.tokopedia.com":    "is Tokopedia's GraphQL endpoint, not a page — "
                            "this scraper drives a browser, not the API",
    "images.tokopedia.net": "is Tokopedia's image CDN",
    "www.tokopedia.net":    "is Tokopedia's asset domain, not the storefront",
    "mitra.tokopedia.com":  "is the Mitra Tokopedia agent app, a different "
                            "product with a different catalogue",
}

# Kept for compatibility with the family's shared engine code, which reads a
# locale-to-currency map. Tokopedia has exactly one of each, so this is a
# one-entry table rather than a mechanism.
LOCALE_CURRENCY = {"id": "IDR"}
CURRENCY = "IDR"


def site_host(url: str) -> Optional[str]:
    """The row's `source`: the bare hostname with `www.` stripped."""
    host = (urlsplit(url).hostname or "").lower()
    if not host:
        return None
    return host[4:] if host.startswith("www.") else host


def unsupported_reason(url: str) -> Optional[str]:
    """Why this URL cannot be scraped, or None if it can be."""
    host = (urlsplit(url).hostname or "").lower()
    if not host:
        return "has no hostname"
    if host in UNSUPPORTED:
        return UNSUPPORTED[host]
    if host in HOSTS:
        return None
    if host.endswith(".tokopedia.com") or host.endswith(".tokopedia.net"):
        return ("is a Tokopedia subdomain but not the storefront — this "
                "scraper reads www.tokopedia.com")
    return "is not a Tokopedia address"


def is_supported_host(url: str) -> bool:
    return unsupported_reason(url) is None


def locale_of(url: str) -> str:
    """Tokopedia serves one locale. Present so shared code has it to call."""
    return "id"


def host_currency(url: str) -> str:
    return CURRENCY


