"""
product_parser.py
-----------------
Everything this repo knows about Tokopedia. The engines know how to drive a
browser; this file knows what a Tokopedia page says.

Read this before changing anything here
=======================================

**There is no structured data on a listing page.** Measured on six live
captures, 2026-09-10: zero `application/ld+json` blocks, zero
`__NEXT_DATA__`, zero React-flight payload, zero Apollo state. The grid is
fetched by client-side GraphQL after load and exists only in the rendered
DOM. So the JSON-LD-first design the rest of this family uses has nothing to
be first about, and the URL-pattern path §4 calls a *fallback* is promoted to
primary because there is nothing above it.

A DETAIL page is different: it carries a serialised Apollo cache in an inline
`window.__cache = {…}`, and that is where the real product id, the exact sold
count and the review count live. `parse_product_page` reads it.

**Class names are content hashes and nothing may anchor on them.**

    <span class="+tnoqZhn89+NHUA43BpiJg==">Kopi Hitam Bubuk Robusta …</span>
    <span class="YZHqvX+8TVU2YltRC9S+oA==">Rp7.500</span>

Those are base64 CSS-module hashes; they change on every deploy. The April
2026 prototype in this repo's history anchored on the emotion equivalents and
on `data-testid="linkProductName"`, `linkProductPrice`, `linkProductShopName`
and friends — **every one of those field selectors is now gone**, zero
occurrences on either page kind. What survived five months is the URL
pattern, three container `data-testid`s, and the utility class `flip`.

So the reads here are deliberately TEXT-ORDER based inside a
structurally-scoped tile. That is unusual for this family and it is the right
trade on this site: the tile's reading order ("badge, title, price,
was-price, rating, sold, shop, location") is a design decision Tokopedia has
kept, while the class that wraps each of those is regenerated by a build.

**Two page kinds, two markups, two paginations.** See PAGE KINDS below. This
is amazon-scraper's situation, and the triage lives in `page_flow.py` as data
rather than as three copies of an if-chain across three engines.
"""

