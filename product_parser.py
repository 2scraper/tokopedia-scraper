# The same site answers a listing request in two entirely different shapes,
# and nothing about one predicts the other.
#
#                     search                       category listing
#   URL               /search?st=product&q=…       /p/<cat>/<sub>[/<subsub>]
#   grid container    divSRPContentProducts        data-ssr=productsCategoryL2/L3SSR
